import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const mod={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(new URL('../lib/acquisitionEntry.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module:mod,exports:mod.exports,URL,URLSearchParams});
const resolve=(search='',referrer='',previous=null)=>JSON.parse(JSON.stringify(mod.exports.resolveAcquisitionEntry(search,referrer,'https://dufynd.de',previous)));
assert.deepEqual(resolve('?utm_source=YouTube&utm_campaign=release_week&utm_content=profile'),{source:'youtube',campaign_id:'release_week',content_id:'profile'});
assert.deepEqual(resolve('?src=instagram&cmp=canonical&content=profile&utm_source=youtube&utm_campaign=other'),{source:'instagram',campaign_id:'canonical',content_id:'profile'});
assert.deepEqual(resolve('?utm_source=google&utm_medium=cpc&utm_campaign=search_ad','https://www.google.de/'),{source:'google',campaign_id:'search_ad'});
assert.deepEqual(resolve('?utm_source=unrecognized&utm_medium=cpc','https://google.de/'),{source:'unknown'});
assert.deepEqual(resolve('?utm_source=instagram&utm_campaign=private%40example.com&utm_content=a%20b'),{source:'instagram'});
for(const host of ['instagram.com','l.instagram.com','www.instagram.com'])assert.deepEqual(resolve('',`https://${host}/?secret=not-retained`),{source:'instagram'});
assert.deepEqual(resolve('','https://m.youtube.com/'),{source:'youtube'});
assert.deepEqual(resolve('','https://www.google.de/search?q=private'),{source:'organic'});
assert.deepEqual(resolve('','https://instagram.com.attacker.invalid/'),{source:'referral'});
assert.deepEqual(resolve('','https://other.example/private'),{source:'referral'});
assert.deepEqual(resolve(''),{source:'unknown'});
assert.deepEqual(resolve('','not-a-url'),{source:'unknown'});
const saved={source:'youtube',campaign_id:'launch',content_id:'profile'};
assert.deepEqual(resolve('','https://dufynd.de/start',saved),saved);
assert.deepEqual(resolve('','',saved),saved);
assert.deepEqual(resolve('','https://l.instagram.com/',saved),{source:'instagram'});
assert.deepEqual(resolve('?src=organic&cmp=launch&content=profile','https://dufynd.de/start',saved),{source:'organic',campaign_id:'launch',content_id:'profile'});
console.log('Acquisition entry: UTM, referrer, precedence, privacy and no-evidence cases PASS');
